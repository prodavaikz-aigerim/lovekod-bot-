async def generate_full_report(disc_scores: dict, love_lang_scores: dict, male_scores: dict = None):
    """Генерирует полный отчёт через Claude API — соло или парный, в
    зависимости от того, передан ли male_scores.

    Возвращает кортеж (sections, error_reason):
      - при успехе: (список из 15 строк содержания, None)
      - при любой ошибке или если модель вернула не 15 частей:
        (None, короткое текстовое описание причины) — вызывающий код
        подставит фолбэк и покажет причину админу в статусе.
    """
    is_couple = male_scores is not None
    titles = REPORT_SECTION_TITLES_COUPLE if is_couple else REPORT_SECTION_TITLES_SOLO

    if not ANTHROPIC_API_KEY:
        reason = "ANTHROPIC_API_KEY не задан"
        logger.warning("%s — используется склеенный отчёт (фолбэк)", reason)
        return None, reason

    if is_couple:
        prompt = build_couple_report_prompt(disc_scores, love_lang_scores, male_scores)
    else:
        prompt = build_solo_report_prompt(disc_scores, love_lang_scores)

    def _call():
        client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY, timeout=45.0)
        response = client.messages.create(
            model=ANTHROPIC_MODEL,
            max_tokens=4096,
            messages=[{"role": "user", "content": prompt}],
        )
        return "".join(block.text for block in response.content if block.type == "text")

    try:
        raw_text = await asyncio.to_thread(_call)
    except Exception as e:
        reason = f"ошибка запроса к Claude API: {e}"
        logger.exception("Не удалось сгенерировать отчёт через Claude API — используется фолбэк")
        return None, reason

    sections = [part.strip() for part in raw_text.split(REPORT_SECTION_DELIMITER)]

    if len(sections) != len(titles):
        reason = f"модель вернула {len(sections)} разделов вместо {len(titles)}"
        logger.warning(
            "Claude API вернул %s разделов вместо %s — используется фолбэк",
            len(sections),
            len(titles),
        )
        return None, reason

    return sections, None


def format_report_html(sections: list, is_couple: bool = False) -> str:
    """Собирает финальный HTML-текст отчёта: жирные заголовки с эмодзи (наши,
    гарантированно валидные) + экранированное содержание от модели (защита
    от случайных символов < > &, которые сломали бы разбор Telegram).
    """
    titles = REPORT_SECTION_TITLES_COUPLE if is_couple else REPORT_SECTION_TITLES_SOLO
    blocks = []
    for i, ((emoji, title), body) in enumerate(zip(titles, sections)):
        escaped_body = html.escape(body)
        blocks.append(f"<b>{i + 1}. {emoji} {title}</b>\n{escaped_body}")
    return "\n\n".join(blocks)


