def build_question_keyboard(qindex: int, options) -> InlineKeyboardMarkup:
    buttons = [
        [InlineKeyboardButton(text=label, callback_data=f"ans|{qindex}|{ptype}")]
        for label, ptype in options
    ]
    return InlineKeyboardMarkup(buttons)


async def send_question(update_or_query, context: ContextTypes.DEFAULT_TYPE, qindex: int):
    question = QUESTIONS[qindex]
    text = f"Вопрос {qindex + 1} из {TOTAL_QUESTIONS}\n\n{question['text']}"
    keyboard = build_question_keyboard(qindex, question["options"])

    if isinstance(update_or_query, Update):
        # Первый вопрос — обычное сообщение (в ответ на /start)
        await update_or_query.message.reply_text(text, reply_markup=keyboard)
    else:
        # CallbackQuery (ответ на предыдущий вопрос) — редактируем то же
        # сообщение, а не создаём новое, чтобы отвеченные вопросы исчезали
        # (раньше здесь была ошибка: CallbackQuery тоже имеет атрибут
        # .message, поэтому старая проверка hasattr всегда попадала в
        # первую ветку и вопросы копились в чате один под другим).
        await update_or_query.edit_message_text(text, reply_markup=keyboard)


def split_text_by_limit(text: str, limit: int) -> list:
    """Режет текст на части не длиннее limit символов, стараясь резать по
    границам абзацев (\\n\\n), чтобы не ломать форматирование. Нужно только
    как страховка от лимита Telegram (4096 символов на сообщение) — в
    подавляющем большинстве случаев вернёт список из одного элемента.
    """
    if len(text) <= limit:
        return [text]

    parts = []
    current = ""
    for paragraph in text.split("\n\n"):
        candidate = f"{current}\n\n{paragraph}" if current else paragraph
        if len(candidate) > limit:
            if current:
                parts.append(current)
            current = paragraph
        else:
            current = candidate
    if current:
        parts.append(current)
    return parts


