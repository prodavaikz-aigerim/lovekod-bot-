def build_multi_keyboard(prefix: str, qindex: int, options) -> InlineKeyboardMarkup:
    """Общая клавиатура 'выбери один из нескольких' — короткие подписи на
    кнопках (2-4 слова), а полная ситуация описана в тексте вопроса. Раньше
    варианты были длинными предложениями прямо на кнопке, и Telegram
    обрезал текст посреди слова, так что прочитать его было невозможно.
    """
    buttons = [
        [InlineKeyboardButton(text=label, callback_data=f"{prefix}|{qindex}|{code}")]
        for label, code in options
    ]
    return InlineKeyboardMarkup(buttons)


