async def handle_male_answer(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer(text="✅ Принято")

    try:
        _, qindex_str, ptype = query.data.split("|")
        qindex = int(qindex_str)
    except (ValueError, AttributeError):
        return

    current_q = context.user_data.get("male_current_q")
    scores = context.user_data.get("male_scores")

    if current_q is None or scores is None:
        await query.edit_message_text(
            "⚠️ Результаты не сохранились (бот перезапускался). Нажми "
            "«Узнать психотип партнёра» ещё раз."
        )
        return

    if qindex != current_q:
        return

    scores[ptype] = scores.get(ptype, 0) + 1
    next_q = current_q + 1
    context.user_data["male_current_q"] = next_q

    if next_q < TOTAL_MALE_QUESTIONS:
        await send_male_question(query, context, next_q)
    else:
        await show_male_result(query, context, scores)


